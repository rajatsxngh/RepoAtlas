"""The file inventory: which files are source code, and why the others are skipped (ING-2..5).

Only files with a source extension are inventoried. Each gets a language, line count, test flag,
and — when it won't be parsed — a skip reason. Rules run cheapest first, so most skips never
read file contents.
"""

from __future__ import annotations

from collections import Counter
from typing import Literal

from pydantic import BaseModel, ConfigDict

from repoatlas.ingest.errors import RepoTooLarge
from repoatlas.ingest.source import GITLINK_MODE, SYMLINK_MODE, SourceTree, TreeEntry

Language = Literal["py", "ts", "js"]
SkipReason = Literal[
    "declaration",
    "symlink",
    "submodule",
    "vendored",
    "generated",
    "too_large",
    "lfs_pointer",
    "binary",
]

_EXTENSIONS: dict[str, Language] = {
    ".py": "py",
    ".ts": "ts",
    ".mts": "ts",
    ".cts": "ts",
    ".tsx": "ts",
    ".js": "js",
    ".mjs": "js",
    ".cjs": "js",
    ".jsx": "js",
}
_DECLARATION_SUFFIXES = (".d.ts", ".d.mts", ".d.cts", ".pyi")
_GENERATED_SUFFIXES = (".min.js", ".min.mjs", ".min.cjs", ".bundle.js")
_GENERATED_MARKERS = (
    b"@generated",
    b"do not edit",
    b"autogenerated",
    b"auto-generated",
    b"code generated by",
)
# Skipped wherever they appear in a path.
_VENDORED_ANYWHERE = frozenset(
    {
        "node_modules",
        "bower_components",
        "vendor",
        "_vendor",
        "third_party",
        "site-packages",
        ".venv",
        "venv",
        "__pycache__",
        ".next",
        ".nuxt",
        ".tox",
    }
)
# Skipped only as top-level folders ("build" is also a common package name).
_VENDORED_TOP_LEVEL = frozenset({"dist", "build", "out", "coverage"})
_TEST_DIRS = frozenset({"test", "tests", "__tests__"})
_LFS_PREFIX = b"version https://git-lfs.github.com/spec/v1"
_BINARY_SNIFF_BYTES = 8000
_MINIFIED_MIN_BYTES = 20_000
_MINIFIED_LINE_LENGTH = 5_000


class FileEntry(BaseModel):
    model_config = ConfigDict(frozen=True)

    path: str
    mode: str
    blob_oid: str
    size: int | None
    language: Language
    is_test: bool
    loc: int | None
    skip_reason: SkipReason | None


class InventoryStats(BaseModel):
    model_config = ConfigDict(frozen=True)

    tree_entries: int
    source_files: int
    indexed: int
    indexed_by_language: dict[str, int]
    skipped: dict[str, int]


class Inventory(BaseModel):
    model_config = ConfigDict(frozen=True)

    files: list[FileEntry]
    stats: InventoryStats

    @property
    def indexed(self) -> list[FileEntry]:
        return [entry for entry in self.files if entry.skip_reason is None]


def language_for(path: str) -> Language | None:
    """The language of a path by extension, or ``None`` if it isn't source code."""
    name = path.rsplit("/", 1)[-1].lower()
    dot = name.rfind(".")
    return _EXTENSIONS.get(name[dot:]) if dot > 0 else None


def is_test_path(path: str, language: Language) -> bool:
    """Test files by folder (``test/``, ``tests/``, ``__tests__/``) or naming convention."""
    *folders, name = path.split("/")
    if any(folder in _TEST_DIRS for folder in folders):
        return True
    if language == "py":
        return name.startswith("test_") or name.endswith("_test.py") or name == "conftest.py"
    return ".test." in name or ".spec." in name


def build_inventory(tree: SourceTree, *, max_source_files: int, max_file_bytes: int) -> Inventory:
    """Classify every source file in ``tree``; raise ``RepoTooLarge`` past the file cap."""
    entries = tree.entries()
    files: list[FileEntry] = []
    for entry in entries:
        language = language_for(entry.path)
        if language is None and not entry.path.lower().endswith(_DECLARATION_SUFFIXES):
            continue
        lang: Language = language or ("py" if entry.path.lower().endswith(".pyi") else "ts")
        reason, loc = _classify(tree, entry, max_file_bytes)
        files.append(
            FileEntry(
                path=entry.path,
                mode=entry.mode,
                blob_oid=entry.oid,
                size=entry.size,
                language=lang,
                is_test=is_test_path(entry.path, lang),
                loc=loc,
                skip_reason=reason,
            )
        )

    indexed = [entry for entry in files if entry.skip_reason is None]
    if len(indexed) > max_source_files:
        raise RepoTooLarge(
            f"The repository has {len(indexed):,} source files after filtering; "
            f"the limit is {max_source_files:,}."
        )
    stats = InventoryStats(
        tree_entries=len(entries),
        source_files=len(files),
        indexed=len(indexed),
        indexed_by_language=dict(sorted(Counter(e.language for e in indexed).items())),
        skipped=dict(sorted(Counter(e.skip_reason for e in files if e.skip_reason).items())),
    )
    return Inventory(files=files, stats=stats)


def _classify(
    tree: SourceTree, entry: TreeEntry, max_file_bytes: int
) -> tuple[SkipReason | None, int | None]:
    lowered = entry.path.lower()
    if lowered.endswith(_DECLARATION_SUFFIXES):
        return "declaration", None
    if entry.mode == SYMLINK_MODE:
        return "symlink", None
    if entry.mode == GITLINK_MODE:
        return "submodule", None
    folders = entry.path.split("/")[:-1]
    if any(f in _VENDORED_ANYWHERE for f in folders) or (
        folders and folders[0] in _VENDORED_TOP_LEVEL
    ):
        return "vendored", None
    if lowered.endswith(_GENERATED_SUFFIXES):
        return "generated", None
    if entry.size is not None and entry.size > max_file_bytes:
        return "too_large", None

    data = tree.read(entry)
    if data.startswith(_LFS_PREFIX):
        return "lfs_pointer", None
    if b"\0" in data[:_BINARY_SNIFF_BYTES]:
        return "binary", None
    lines = data.split(b"\n")
    header = b"\n".join(lines[:5]).lower()
    if any(marker in header for marker in _GENERATED_MARKERS):
        return "generated", None
    if len(data) > _MINIFIED_MIN_BYTES and max(map(len, lines)) > _MINIFIED_LINE_LENGTH:
        return "generated", None
    return None, sum(1 for line in lines if line.strip())
