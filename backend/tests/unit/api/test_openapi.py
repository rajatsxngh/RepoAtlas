"""The OpenAPI spec and the TypeScript types generated from it: committed, current, complete."""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

from typer.testing import CliRunner

from repoatlas.api.openapi import openapi_spec, render_spec
from repoatlas.cli import app

BACKEND = Path(__file__).resolve().parents[3]
SPEC = BACKEND / "openapi.json"
TYPES = BACKEND.parent / "frontend" / "src" / "lib" / "api" / "schema.d.ts"
STALE = (
    "backend/openapi.json is out of date. In backend/, run: "
    "uv run repoatlas api openapi --out openapi.json, then regenerate the web app's types "
    "with scripts/gen_api_types.sh (or .ps1), and commit both files."
)
ENDPOINTS = {
    ("post", "/api/v1/repos"): "build_repo",
    ("get", "/api/v1/jobs/{job_id}"): "get_job_status",
    ("get", "/api/v1/snapshots/{snapshot_id}"): "get_snapshot",
    ("get", "/api/v1/snapshots/{snapshot_id}/subgraph"): "get_subgraph",
    ("get", "/api/v1/snapshots/{snapshot_id}/nodes/{key}"): "get_node",
    ("get", "/api/v1/snapshots/{snapshot_id}/nodes/{key}/neighbors"): "get_neighbors",
    ("get", "/api/v1/snapshots/{snapshot_id}/locate"): "locate_line",
    ("get", "/api/v1/snapshots/{snapshot_id}/search"): "search_symbols",
    ("get", "/api/v1/snapshots/{snapshot_id}/path"): "find_path",
    ("get", "/api/v1/snapshots/{snapshot_id}/code"): "read_code",
    ("get", "/api/v1/health"): "health",
    ("get", "/api/v1/ready"): "ready",
}
ERROR_REF = "#/components/schemas/ErrorResponse"


def test_the_committed_spec_is_current() -> None:
    assert SPEC.is_file(), STALE
    assert SPEC.read_text(encoding="utf-8") == render_spec(), STALE


def test_the_spec_does_not_depend_on_hash_seeds() -> None:
    code = "import sys; from repoatlas.api.openapi import render_spec; "
    code += "sys.stdout.buffer.write(render_spec().encode('utf-8'))"
    env = {**os.environ, "PYTHONHASHSEED": "12345"}
    result = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, env=env, check=True, timeout=120
    )
    assert result.stdout.decode("utf-8") == render_spec()


def test_every_endpoint_is_in_the_spec_with_its_errors() -> None:
    spec = openapi_spec()
    found = {
        (method, path): operation["operationId"]
        for path, operations in spec["paths"].items()
        for method, operation in operations.items()
    }
    assert found == ENDPOINTS
    for (method, path), _ in ENDPOINTS.items():
        responses = spec["paths"][path][method]["responses"]
        if path.endswith(("/health", "/ready")):
            continue
        for status in ("422", "429", "500"):
            schema = responses[status]["content"]["application/json"]["schema"]
            assert schema == {"$ref": ERROR_REF}, (path, status)
        if "/snapshots/{snapshot_id}/" in path:
            assert {"404", "409"} <= set(responses), path
    assert "HTTPValidationError" not in spec["components"]["schemas"]  # ours replaces it
    codes = spec["components"]["schemas"]["ErrorCode"]["enum"]
    assert "snapshot_not_ready" in codes and "rate_limited" in codes


def test_the_typescript_types_were_generated_from_this_spec() -> None:
    """A proxy that runs without Node; CI regenerates the types and compares them exactly."""
    text = TYPES.read_text(encoding="utf-8")
    assert text.startswith("/**\n * This file was auto-generated by openapi-typescript."), TYPES
    assert "\r" not in text
    spec = openapi_spec()
    declared = set(re.findall(r'^    "(/api/v1/[^"]*)": \{$', text, re.MULTILINE))
    assert declared == set(spec["paths"]), "regenerate with scripts/gen_api_types.sh"
    for operation_id in ENDPOINTS.values():
        assert f"    {operation_id}: {{" in text, operation_id
    for name in spec["components"]["schemas"]:
        assert re.search(rf"^        {re.escape(name)}: ", text, re.MULTILINE), name


def test_the_export_command_writes_and_checks_the_spec(tmp_path: Path) -> None:
    out = tmp_path / "openapi.json"
    runner = CliRunner()
    written = runner.invoke(app, ["api", "openapi", "--out", str(out)])
    assert written.exit_code == 0, written.output
    assert out.read_bytes() == render_spec().encode("utf-8")  # LF line endings on every OS
    current = runner.invoke(app, ["api", "openapi", "--out", str(out), "--check"])
    assert current.exit_code == 0 and "up to date" in current.output
    out.write_text(out.read_text(encoding="utf-8").replace("RepoAtlas API", "Old API"), "utf-8")
    stale = runner.invoke(app, ["api", "openapi", "--out", str(out), "--check"])
    assert stale.exit_code == 1 and "out of date" in stale.output
    assert "Old API" in out.read_text(encoding="utf-8")  # --check never writes
    missing = runner.invoke(app, ["api", "openapi", "--out", str(tmp_path / "x.json"), "--check"])
    assert missing.exit_code == 1
    printed = runner.invoke(app, ["api", "openapi", "--out", "-"])
    assert printed.exit_code == 0 and json.loads(printed.stdout)["info"]["title"] == "RepoAtlas API"
