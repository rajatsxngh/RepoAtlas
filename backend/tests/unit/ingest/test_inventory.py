def test_skipped_files_have_no_loc_and_stats_count_reasons() -> None:
    inv = inventory(
        {
            "node_modules/a.js": b"x\n",
            "node_modules/b.js": b"y\n",
            "types.d.ts": b"declare const x: 1;\n",
            "ok.ts": b"export const x = 1;\n",
        }
    )
    assert all(entry.loc is None for entry in inv.files if entry.skip_reason)
    assert inv.stats.skipped == {"declaration": 1, "vendored": 2}
    assert [entry.path for entry in inv.indexed] == ["ok.ts"]


def test_source_file_cap() -> None:
    files: dict[str, bytes | tuple[str, bytes]] = {f"m{i}.py": b"x = 1\n" for i in range(4)}
    files["node_modules/skipped.js"] = b"x\n"
    assert inventory(files, max_source_files=4).stats.indexed == 4
    with pytest.raises(RepoTooLarge, match="limit is 3"):
        inventory(files, max_source_files=3)


def test_inventory_is_deterministic() -> None:
    files: dict[str, bytes | tuple[str, bytes]] = {
        "b.py": b"b = 1\n",
        "a/c.ts": b"export const c = 1;\n",
    }
    first = inventory(files).model_dump_json()
    second = inventory(dict(reversed(list(files.items())))).model_dump_json()
    assert first == second
