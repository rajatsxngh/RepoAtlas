from __future__ import annotations

import pytest

from repoatlas.ingest.errors import RepoTooLarge
from repoatlas.ingest.inventory import Inventory, build_inventory, is_test_path, language_for
from repoatlas.ingest.source import MemorySourceTree


def inventory(files: dict[str, bytes | tuple[str, bytes]], **caps: int) -> Inventory:
    limits = {"max_source_files": 100, "max_file_bytes": 50_000, **caps}
    return build_inventory(MemorySourceTree(files), **limits)


def reasons(inv: Inventory) -> dict[str, str | None]:
    return {entry.path: entry.skip_reason for entry in inv.files}


@pytest.mark.parametrize(
    ("path", "language"),
    [
        ("app/main.py", "py"),
        ("src/index.ts", "ts"),
        ("src/App.tsx", "ts"),
        ("src/mod.mts", "ts"),
        ("src/mod.cts", "ts"),
        ("lib/index.js", "js"),
        ("lib/index.mjs", "js"),
        ("lib/index.cjs", "js"),
        ("src/Button.jsx", "js"),
        ("SRC/UPPER.PY", "py"),
        ("README.md", None),
        ("package.json", None),
        ("Makefile", None),
        (".py", None),
        ("stubs/mod.pyi", None),
    ],
)
def test_language_for(path: str, language: str | None) -> None:
    assert language_for(path) == language


